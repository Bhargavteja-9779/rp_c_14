"""Assemble supplementary/Supplementary_Material.md|docx from the machine-generated tables."""
import os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import pandas as pd
T = os.path.join(ROOT, "tables")
ITEMS = [
 ("table_main_accuracy_confirm", "Mean test accuracy on the confirmation datasets (in neither the development nor the design set)", 100),
 ("table_main_accuracy_heldout", "Mean test accuracy on all datasets outside the 12-dataset development set", 100),
 ("table_main_accuracy_nodup", "Mean test accuracy after excluding datasets with more than 1% exact train–test duplicates", 100),
 ("table_main_balanced_accuracy", "Mean balanced accuracy, all datasets", 100),
 ("table_main_macro_f1", "Mean macro-F1, all datasets", 100),
 ("table_seed_std", "Standard deviation over the five resample seeds of the across-dataset mean accuracy", 100),
 ("table_mean_ranks", "Mean rank of each method per condition (1 = best)", 1),
 ("stats_loo_em_bic_vs_ridge_wide_all", "LOO-EM (BIC) versus wide-grid ridge, all datasets (includes design data)", None),
 ("stats_loo_em_bic_vs_ridge_std_confirm", "LOO-EM (BIC) versus default-grid ridge, confirmation datasets", None),
 ("stats_ridge_wide_vs_ridge_std_confirm", "Wide versus default grid, confirmation datasets", None),
 ("stats_loo_em_vs_ridge_wide_all", "LOO-EM v1 versus wide-grid ridge, all datasets", None),
 ("stats_conf_learning_vs_ridge_wide_all", "Confident learning versus wide-grid ridge, all datasets", None),
 ("stats_conf_learning_cal_vs_ridge_wide_all", "Confident learning with temperature-calibrated probabilities versus wide-grid ridge, all datasets", None),
 ("stats_conf_learning_cal_vs_conf_learning_all", "Calibrated versus uncalibrated confident learning, all datasets", None),
 ("stats_enn_vs_ridge_wide_all", "Edited nearest neighbours versus wide-grid ridge, all datasets", None),
 ("stats_loo_relabel_vs_ridge_wide_all", "One-round LOO relabelling versus wide-grid ridge, all datasets", None),
 ("stats_loo_remove_vs_ridge_wide_all", "LOO removal versus wide-grid ridge, all datasets", None),
 ("stats_secondary", "Paired comparisons in the secondary experiments (Holm correction within each comparison)", None),
 ("table_det_auroc", "AUROC of label-error detection", 1),
 ("table_det_f1", "F1 of the binary flagged / not-flagged decision", 1),
 ("table_label_acc", "Fraction of correct training labels after cleaning", 100),
 ("table_em_diagnostics", "EM diagnostics: fraction of runs in which a noise model is accepted, estimated and true noise rate, iterations", None),
 ("table_by_train_size", "Mean accuracy by training-set size", None),
 ("table_by_n_classes", "Mean accuracy by number of classes", None),
 ("table_by_imbalance", "Mean accuracy and balanced accuracy by class-imbalance ratio of the training set", None),
 ("table_sensitivity", "Sensitivity study (30 datasets, seeds 0–2): mean accuracy per method variant and number of kernels", None),
 ("table_large", "The largest UCR datasets (seeds 0–2)", 100),
 ("table_large_timing", "Timing on the largest UCR datasets (seconds)", None),
 ("table_error_analysis", "Largest per-dataset losses and gains of LOO-EM (BIC) relative to wide-grid ridge", None),
 ("table_error_correlates", "Spearman correlation of the per-dataset gain with dataset properties", None),
 ("table_leakage_audit", "Duplicate audit of the archive's default train/test splits (datasets with at least one exact duplicate)", None),
]
out = ["---\ntitle: \"Supplementary material: Regularise before you relabel\"\n---\n",
       "All tables are generated by `python run_all.py --mode report` from the raw per-run results; none is edited by hand. "
       "S, A and B (or sym, asym, boundary) denote symmetric, asymmetric and boundary noise at the given rate.\n"]
k = 0
for name, cap, scale in ITEMS:
    f = os.path.join(T, name + ".csv")
    if not os.path.exists(f):
        continue
    df = pd.read_csv(f)
    if name == "table_leakage_audit":
        df = df[df.exact_dup_train_test > 0]
    num = df.select_dtypes("number").columns
    if scale == 100:
        df[num] = (100 * df[num]).round(1)
    else:
        df[num] = df[num].round(4)
    df = df.rename(columns={df.columns[0]: "Method" if df.columns[0].startswith("Unnamed") else df.columns[0]})
    k += 1
    out.append(f"\n**Table S{k}** {cap}" + (" (%)" if scale == 100 else "") + "\n\n" + df.to_markdown(index=False) + "\n")
out.append("\n# Experimental protocol and design history\n\n" + open(os.path.join(ROOT, "supplementary", "protocol.md")).read().replace("\n# ", "\n## ").lstrip("# "))
md = os.path.join(ROOT, "supplementary", "Supplementary_Material.md")
open(md, "w").write("\n".join(out))
docx = md.replace(".md", ".docx")
subprocess.check_call(["pandoc", md, "-o", docx])
from manuscript import docx_format
docx_format.polish(docx)
print("supplement:", k, "tables ->", docx)
